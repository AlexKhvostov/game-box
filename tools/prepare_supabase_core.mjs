import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {patchCurrentGame} from './supabase_current_game_patch.mjs';
import {patchInviteShortCodes} from './supabase_invite_short_patch.mjs';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out=path.join(root,'supabase/functions/_shared/core');
fs.mkdirSync(out,{recursive:true});
const header='// Generated by tools/prepare_supabase_core.mjs from the reviewed game engine.\n// Rebuild after changing the source; the generated copy has no Firebase runtime dependency.\n';
for(const name of ['policy','engine','play']) {
  let source=fs.readFileSync(path.join(root,`firebase-android/functions/src/${name}.js`),'utf8');
  source=source.replace(/^'use strict';\r?\n/,'');
  if(name==='engine')source="import {Buffer} from 'node:buffer';\n"+source;
  source=source.replace(/const crypto = require\('node:crypto'\);/g,"import crypto from 'node:crypto';");
  source=source.replace(/const \{GoogleAuth\} = require\('google-auth-library'\);/,"import {GoogleAuth} from 'google-auth-library';");
  source=source.replace(/const defaults = require\('\.\.\/config\/defaults.json'\);/,"import defaults from './defaults.json' with {type:'json'};");
  source=source.replace(/const (\{[^\n]+\}) = require\('\.\/policy'\);/,"import $1 from './policy.mjs';");
  source=source.replace(/module\.exports=(\{[^\n]+\});?/, 'export $1;');
  source=source.replace(/module\.exports = (\{[^\n]+\});?/, 'export $1;');
  source=source.replaceAll('firebase:${uid}','supabase:${uid}');
  source=source.replaceAll("source:'firebase'","source:'supabase'");
  // The live API supplies the trusted Auth lookup. In isolated SQL tests the
  // inviter snapshot is already read in this transaction: do not borrow a
  // second connection to repeat that read (single-connection pools deadlock).
  if(name==='engine') source=source.replace('inviterSnap.data().googleLinked && await linked(p.inviterUid)',
    'inviterSnap.data().googleLinked && (googleLinkedForUid ? await linked(p.inviterUid) : true)');
  if(name==='engine') source=source.replace('p.googleLinked=identity.googleLinked;',
    "requireThat(!p.supportDisabled,'profile_disabled',403);p.googleLinked=identity.googleLinked;")
    .replace('p.version++;put(ref,p);','if(!identity.background)p.lastActiveAt=stamp;p.version++;put(ref,p);')
    .replace("{googleLinked:true});", "{googleLinked:true,background:true});")
    .replace("requireThat(!old.exists || old.data().uid === uid,'purchase_owner_invalid');",
      "requireThat(!old.exists || old.data().uid === uid,'purchase_owner_invalid');requireThat(!old.exists || !old.data().revoked,'purchase_canceled');")
    .replace('put(rr,{uid:p.uid,fingerprint,',"put(rr,{uid:p.uid,platform:'android',fingerprint,")
    .replace('{...result,id:roundId,userId:',"{...result,platform:'android',id:roundId,userId:")
    .replace("db.collection('scores').where('timeMs'", "db.collection('scores').where('platform','==','android').where('timeMs'")
    .replace('periods[period].map(r=>decorated.get(r.id))','periods[period].map(r=>decorated.get(r.id)).filter(Boolean)');
  if(name==='engine') source=source.replace('return rows.map(row=>{const p=profiles.get(row.uid);',
    'return rows.filter(row=>profiles.has(row.uid) && !profiles.get(row.uid).supportDisabled).map(row=>{const p=profiles.get(row.uid);');
  if(name==='engine')source=patchCurrentGame(source);
  if(name==='engine')source=patchInviteShortCodes(source);
  if(name==='play') source=source.replace('function createPlayVerifier({request} = {})','function createPlayVerifier({request,credentials} = {})').replace("new GoogleAuth({scopes:","new GoogleAuth({credentials,scopes:");
  if(/require\(|module\.exports/.test(source)) throw Error(`Unconverted CommonJS in ${name}`);
  fs.writeFileSync(path.join(out,`${name}.mjs`),header+source);
}
fs.copyFileSync(path.join(root,'assets/config/android-firebase.json'),path.join(out,'defaults.json'));
console.log('Supabase ESM game core generated (no Firebase Auth/Firestore SDK).');
