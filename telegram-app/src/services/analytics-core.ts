export type AnalyticsEvent = typeof analyticsEvents[number];
const allowed = new Set<string>(analyticsEvents);
export const isAnalyticsEvent = (name:string):name is AnalyticsEvent => allowed.has(name);
export const windowEvent = (name:string) => {const event=`window_${name}_open`;return isAnalyticsEvent(event)?event:null;};
export const clickEvent = (placement:string,feature:string) => {const event=`click_${placement}_${feature}`;return isAnalyticsEvent(event)?event:null;};
export class WindowAnalytics {
 private stack:string[]=[];
 constructor(private emit:(name:AnalyticsEvent)=>void){}
 setStack(next:string[]){let common=0;while(common<next.length&&next[common]===this.stack[common])common++;for(const name of next.slice(common)){const event=windowEvent(name);if(event)this.emit(event);}this.stack=[...next];}
}
